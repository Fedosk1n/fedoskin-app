export const landmarkImage = id => `img/city-guide-${id}.webp?v=1`;
export const WATCH_SIZE = { x: .59, z: .49 };
export function inWatchArea(point, player) {
  return ((point.x - player.x) / WATCH_SIZE.x) ** 2 + ((point.z - player.z) / WATCH_SIZE.z) ** 2 <= 1;
}


export function placeLandmark(id, point, colliders, bounds) {
  if (!point || id === 'watch') return point;
  const clear = (x,z) => x >= bounds.x0+.43 && x <= bounds.x1-.43 && z >= bounds.z0+.43 && z <= bounds.z1-.43 &&
    !colliders.some(c => c.r != null ? Math.hypot(x-c.x,z-c.z) <= c.r+.48 :
      x > c.x0-.48 && x < c.x1+.48 && z > c.z0-.48 && z < c.z1+.48);
  for (const [dx,dz] of [[0,-.60],[-.64,-.30],[.64,-.30],[-.63,.25],[.63,.25],[0,.59],[0,0]]) {
    const x=point.x+dx, z=point.z+dz;
    if (clear(x,z)) return { ...point, x, z, yaw:Math.atan2(-dx,-dz) };
  }
  return point;
}
